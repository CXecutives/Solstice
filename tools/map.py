#!/usr/bin/env python3
"""Write MAP.md: every source file with its purpose, taken from the comment at the top of the file.

    python3 tools/map.py           writes MAP.md
    python3 tools/map.py --check   also fails when a file has no purpose line

The purpose is the first sentence of a file's leading comment, so the map cannot drift from the code:
change the comment, run tools/regen.sh.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIRS = ["core", "host", "devices", "ios/Henge", "ios/HengeJITHelper", "ios/scripts", "tools", "tests"]
EXTS = {".c", ".h", ".m", ".S", ".swift", ".py", ".sh", ".zsh", ".ps1", ".def"}
SKIP = re.compile(r"^(#!|#\s*(include|import|pragma|if|ifndef|ifdef|define|endif)\b|SPDX|@|import\b|\"\"\"\s*$)")
MARK = re.compile(r"^\s*(///?|/\*+|\*+/?|#+|;+|<#|\"\"\")\s?")


def purpose(path: pathlib.Path) -> str:
    """The first sentence of the file's leading comment, or ''."""
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()[:25]
    except OSError:
        return ""
    words, started, block = [], False, ""  # block: the closer of an open /* ... */ or docstring
    for raw in lines:
        line = raw.strip()
        if not line:
            if started:
                break
            continue
        if "SPDX-License-Identifier" in line:
            continue
        is_comment = bool(block) or (bool(MARK.match(raw)) and not SKIP.match(line)) or line.startswith('"""')
        if not is_comment:
            if started:
                break
            if SKIP.match(line):
                continue
            break  # code before any comment: no header
        if not block:
            if line.startswith("/*") and "*/" not in line:
                block = "*/"
            elif line.startswith('"""') and line.count('"""') == 1:
                block = '"""'
        elif block in line:
            block = ""
        text = MARK.sub("", raw).strip().replace('"""', "").rstrip("*/").strip()
        if text.startswith(path.name):  # "name.c: what it does" or a bare file-name line
            text = text[len(path.name):].lstrip(" :-–—")
        if not text:
            if started:
                break
            continue
        started = True
        words.append(text)
        if re.search(r"[.!?]$", text) or len(" ".join(words)) > 240:
            break
    sentence = " ".join(words)
    m = re.match(r"(.+?[.!?])(\s|$)", sentence)
    return (m.group(1) if m else sentence).strip()


def main() -> int:
    check = "--check" in sys.argv
    out, missing = ["# Map", "", "Every source file and what it is for. Generated by `tools/map.py` from each file's top comment; "
                    "do not edit by hand (run `tools/regen.sh`).", ""], []
    for d in DIRS:
        base = ROOT / d
        if not base.is_dir():
            continue
        files = sorted(p for p in base.rglob("*") if p.is_file() and p.suffix in EXTS and "build" not in p.parts
                       and "deps" not in p.parts)
        if not files:
            continue
        out.append(f"## {d}")
        for p in files:
            rel = p.relative_to(ROOT).as_posix()
            what = purpose(p)
            if not what:
                missing.append(rel)
                what = "(no purpose line yet)"
            out.append(f"- `{rel}`: {what}")
        out.append("")
    (ROOT / "MAP.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    if missing:
        print(f"map: {len(missing)} files without a purpose line:\n  " + "\n  ".join(missing))
    return 1 if check and missing else 0


if __name__ == "__main__":
    sys.exit(main())

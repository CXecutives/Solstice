#!/usr/bin/env python3
"""Write what is generated from the engine's settings table (core/knobs.def), or check that nothing goes around it.

    python3 tools/knobs.py           writes ios/Henge/EngineKnobs.generated.swift and KNOBS.md
    python3 tools/knobs.py --check   fails on a getenv("HV_...") outside core/knobs.c, or an HV_ name used in the app,
                                     the tests, tools/, the Makefile or the workflow that is not in the table

Other tools read the table through table() (tools/shipped_env.py).
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEF = ROOT / "core" / "knobs.def"
SWIFT = ROOT / "ios" / "Henge" / "EngineKnobs.generated.swift"
DOC = ROOT / "KNOBS.md"
LINE = re.compile(r'^KNOB\((\w+), "(HV_\w+)", (FLAG|BOOL|INT|DOUBLE|HEX|STR), (.+?), (.+?), (.+?), "(.*)"\)$')
SECTION = re.compile(r"^/\* ---- (.+?) ---- \*/$")
HEADER = "Generated by tools/knobs.py from core/knobs.def: do not edit (run tools/regen.sh)."


class Knob:
    def __init__(self, field, name, kind, default, lo, hi, doc, section):
        self.field, self.name, self.kind, self.default, self.lo, self.hi = field, name, kind, default, lo, hi
        self.doc, self.section = doc.replace('\\"', '"'), section

    @property
    def swift(self) -> str:
        head, *rest = self.field.split("_")
        return head + "".join(w[:1].upper() + w[1:] for w in rest)

    def check(self, value: str) -> str:
        """'' if value is what this setting takes (as core/knobs.c parses it), else why not."""
        if self.kind not in ("INT", "DOUBLE"):
            return ""
        num = r"[+-]?\d+" if self.kind == "INT" else r"[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?"
        if not re.fullmatch(num, value.strip()):
            return f"not a number"
        lo, hi = (plain(self.lo), plain(self.hi))
        v = float(value)
        if (lo is not None and v < lo) or (hi is not None and v > hi):
            return f"outside {self.lo}..{self.hi}"
        return ""


def plain(text: str):
    """A bound as a number (None for INT_MIN/INT_MAX)."""
    if text in ("INT_MIN", "INT_MAX"):
        return None
    return float(text.rstrip("ulUL")) if not text.startswith("0x") else float(int(text.rstrip("ulUL"), 16))


def table() -> list:
    knobs, section, problems = [], "", []
    for n, raw in enumerate(DEF.read_text(encoding="utf-8").splitlines(), 1):
        s = SECTION.match(raw.strip())
        if s:
            section = s.group(1)
        if not raw.startswith("KNOB("):
            continue
        m = LINE.match(raw)
        if not m:
            problems.append(f"core/knobs.def:{n}: not a KNOB(field, \"HV_NAME\", TYPE, default, low, high, \"purpose\") line")
            continue
        k = Knob(*m.groups(), section)
        if k.name != "HV_" + k.field.upper():
            problems.append(f"core/knobs.def:{n}: {k.name} should be named HV_{k.field.upper()} (one name per setting)")
        if any(k.name == o.name for o in knobs):
            problems.append(f"core/knobs.def:{n}: {k.name} twice")
        knobs.append(k)
    if problems:
        sys.exit("\n".join(problems))
    return knobs


def write(path: pathlib.Path, text: str) -> None:
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def swift(knobs) -> str:
    out = [f"// {HEADER}", "", "/// The engine's settings (core/knobs.def) by name, so the app cannot misspell one.",
           "enum EngineKnob: String, CaseIterable {"]
    for k in knobs:
        out.append(f"    /// {k.doc}")
        out.append(f'    case {k.swift} = "{k.name}"')
    out.append("}")
    return "\n".join(out) + "\n"


def doc(knobs) -> str:
    def shown(k):
        default = {"NULL": "unset"}.get(k.default, k.default.strip('"'))
        if k.kind == "HEX":
            default = default.rstrip("ulUL")
        rng = f"{k.lo}..{k.hi}".replace("INT_MIN", "min").replace("INT_MAX", "max") if k.kind in ("INT", "DOUBLE") else ""
        return default, rng
    out = ["# Engine settings", "", f"<!-- {HEADER} -->", "",
           "Environment variables the engine reads, all from `core/knobs.def`. The app sets them from "
           "`ios/Henge/EngineTuning.swift` and `Documents/solstice-env.txt`; the Mac tool and the tests take them from "
           "the environment. FLAG: on when set at all; BOOL: 0 off, other numbers or empty on; INT and DOUBLE outside "
           "their range fall back to the default."]
    section = None
    for k in knobs:
        if k.section != section:
            section = k.section
            out += ["", f"## {section}", "", "| Name | Type | Default | Range | Purpose |", "|---|---|---|---|---|"]
        default, rng = shown(k)
        out.append(f"| `{k.name}` | {k.kind.lower()} | {default} | {rng} | {k.doc.replace('|', '/')} |")
    return "\n".join(out) + "\n"


def check(knobs) -> int:
    names = {k.name for k in knobs}
    bad = []
    for d in ("core", "host", "devices", "ios", "tools"):
        for p in (ROOT / d).rglob("*"):
            if p.suffix not in (".c", ".h", ".m", ".mm") or p == ROOT / "core" / "knobs.c" or "deps" in p.parts:
                continue
            for n, line in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
                if 'getenv("HV_' in line:
                    bad.append(f"{p.relative_to(ROOT)}:{n}: getenv(\"HV_...\") outside core/knobs.c: read hv_knob instead")
    used = []  # (where, name)
    literal, assign = re.compile(r'"(HV_[A-Z0-9_]+)"'), re.compile(r"\b(HV_[A-Z0-9_]+)=")
    sources = [(p, (literal,)) for p in (ROOT / "ios").rglob("*.swift")]
    sources += [(p, (literal, assign)) for p in (ROOT / "tests").rglob("*") if p.is_file()]
    sources += [(p, (literal, assign)) for p in (ROOT / "tools").rglob("*") if p.is_file() and p.name != "knobs.py"]
    sources += [(p, (assign,)) for p in [ROOT / "Makefile", *(ROOT / ".github" / "workflows").glob("*.yml")]]
    for p, pats in sources:
        try:
            text = p.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        for n, line in enumerate(text.splitlines(), 1):
            for pat in pats:
                used += [(f"{p.relative_to(ROOT)}:{n}", m) for m in pat.findall(line)]
    bad += [f"{where}: {name} is not in core/knobs.def" for where, name in used if name not in names]
    print("\n".join(bad) if bad else f"knobs: {len(knobs)} settings, {len(used)} uses checked")
    return 1 if bad else 0


def main() -> int:
    knobs = table()
    if "--check" in sys.argv:
        return check(knobs)
    write(SWIFT, swift(knobs))
    write(DOC, doc(knobs))
    return 0


if __name__ == "__main__":
    sys.exit(main())
